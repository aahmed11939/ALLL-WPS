def _set_cell_shading(cell, hex_color: str) -> None:
    tc   = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd  = OxmlElement("w:shd")
    shd.set(qn("w:val"),   "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"),  hex_color)
    tcPr.append(shd)


def _set_cell_borders(cell, color: str = "BBBBBB") -> None:
    tc      = cell._tc
    tcPr    = tc.get_or_add_tcPr()
    tcBords = OxmlElement("w:tcBorders")
    for side in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{side}")
        el.set(qn("w:val"),   "single")
        el.set(qn("w:sz"),    "4")
        el.set(qn("w:color"), color)
        tcBords.append(el)
    tcPr.append(tcBords)


def _add_page_numbers(doc: Document) -> None:
    """
    Insert « Page X of Y » centre-aligned in every section footer.
    Uses Word's built-in PAGE and NUMPAGES fields.
    """
    for section in doc.sections:
        footer         = section.footer
        footer.is_linked_to_previous = False
        fp = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
        fp.clear()
        fp.alignment = WD_ALIGN_PARAGRAPH.CENTER

        run_pre = fp.add_run("Page ")
        run_pre.font.size = Pt(8)

        # PAGE field
        fld_page = OxmlElement("w:fldChar")
        fld_page.set(qn("w:fldCharType"), "begin")
        fp.runs[-1]._r.append(fld_page)

        instr = OxmlElement("w:instrText")
        instr.text = " PAGE "
        fp.runs[-1]._r.append(instr)

        end_page = OxmlElement("w:fldChar")
        end_page.set(qn("w:fldCharType"), "end")
        fp.runs[-1]._r.append(end_page)

        run_of = fp.add_run(" of ")
        run_of.font.size = Pt(8)

        # NUMPAGES field
        fld_total = OxmlElement("w:fldChar")
        fld_total.set(qn("w:fldCharType"), "begin")
        fp.runs[-1]._r.append(fld_total)

        instr2 = OxmlElement("w:instrText")
        instr2.text = " NUMPAGES "
        fp.runs[-1]._r.append(instr2)

        end_total = OxmlElement("w:fldChar")
        end_total.set(qn("w:fldCharType"), "end")
        fp.runs[-1]._r.append(end_total)


