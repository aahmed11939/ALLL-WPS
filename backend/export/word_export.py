# ---------------------------------------------------------------------------

def _write_timeseries_for_pipeline(doc: Document, label: str, moc: dict | None) -> None:
    """Write first-50-row time-series snapshot for one MOC result."""
    _para(doc, label, bold=True)
    if not moc:
        _para(doc, "  MOC not run for this pipeline.", italic=True)
        doc.add_paragraph()
        return

    obs = moc.get("observations", []) or []
    if not obs:
        _para(doc, "  No observation data.", italic=True)
        doc.add_paragraph()
        return

    for ob in obs:
        node_label = ob.get("label", "Node")
        hist       = ob.get("history", []) or []
        _para(doc, f"  Observation: {node_label}  (x = {_fmt(ob.get('x_m'))} m)", bold=False)

        if not hist:
            _para(doc, "    No time history data.", italic=True)
            doc.add_paragraph()
            continue

        snapshot  = hist[:50]
        headers   = ["t (s)", "H (m)", "P (kPa)"]
        data_rows = [
            [_fmt(h.get("t_s"), 3), _fmt(h.get("H_m")), _fmt(h.get("P_kPa"), 1)]
            for h in snapshot
        ]
        _col_table(doc, headers, data_rows, col_widths=[1.2, 1.2, 1.2])

        if len(hist) > 50:
            _para(doc, f"  … {len(hist) - 50} further row(s) omitted.", italic=True)
        doc.add_paragraph()


def _appendix_surge_timeseries(doc: Document, draft: dict) -> None:
    _heading(doc, "Appendix C — Surge Time-Series Snapshot (first 50 rows per node)")

    suct_moc = draft.get("suctionSurgeResult") or None
    disc_moc = draft.get("mocResult")          or None

    if not suct_moc and not disc_moc:
        _para(doc, "MOC time-series data not available.", italic=True)
        return

    _write_timeseries_for_pipeline(doc, "SUCTION PIPELINE", suct_moc)
    _write_timeseries_for_pipeline(doc, "DISCHARGE PIPELINE", disc_moc)


