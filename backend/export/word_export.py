def _hydraulics_section(doc: Document, draft: dict) -> None:
    _heading(doc, "4. Hydraulic Analysis")

    us  = draft.get("unitSystem", "SI")
    Q   = draft.get("designFlow_m3h", 0) or 0
    hyd = draft.get("hydraulicsResult") or {}

    _heading(doc, "4.1 Friction Loss Method", level=2)
    _para(doc, (
        "Friction head losses are computed using the Darcy-Weisbach equation with "
        "the Swamee-Jain explicit approximation to the Colebrook-White friction factor. "
        "Minor losses are calculated as ΣK·V²/(2g)."
    ))
    doc.add_paragraph()

    _heading(doc, "4.2 Key Equations", level=2)
    _para(doc, "Darcy-Weisbach friction head loss:", bold=True)
    _equation(doc, "hf = f · (L / D) · V² / (2g)")
    _para(doc, "Swamee-Jain (explicit Colebrook-White approximation):", bold=True)
    _equation(doc, "f = 0.25 / [ log10( ε/(3.7·D) + 5.74/Re⁰·⁹ ) ]²")
    _para(doc, "Reynolds number:", bold=True)
    _equation(doc, "Re = ρ·V·D / μ      [turbulent if Re > 4000]")
    _para(doc, "Minor head loss:", bold=True)
    _equation(doc, "hm = ΣK · V² / (2g)")
    _para(doc, "Total Dynamic Head:", bold=True)
    _equation(doc, "TDH = Hs + ΣHf + ΣHm + ΔHpressure + ΔHvelocity")
    doc.add_paragraph()

    # Per-segment Darcy-Weisbach breakdown table
    _heading(doc, "4.3 Per-Segment Hydraulic Breakdown", level=2)
    _para(doc, (
        "The following table shows the computed Darcy-Weisbach friction and minor "
        "losses for each pipe segment at the design flow."
    ))
    doc.add_paragraph()

    headers = [
        "Seg #", "Pipeline", "Material", "DN (mm)", "L (m)",
        "v (m/s)", "Re", "f (D-W)", "Hf (m)", "Hm (m)",
    ]
    data_rows = []
    for pipe_key in ("suction", "discharge"):
        pipe   = draft.get(pipe_key) or {}
        segs   = pipe.get("segments", []) or []
        K_tot  = pipe.get("accessories_K_sum", 0.0) or 0.0
        n_segs = max(len(segs), 1)
        for j, seg in enumerate(segs):
            s      = _seg_darcy(Q, seg)
            K_seg  = K_tot / n_segs
            Hm_seg = K_seg * s["v"] ** 2 / (2 * G_ACC) if s["v"] else 0.0
            data_rows.append([
                str(j + 1),
                pipe_key.capitalize(),
                seg.get("material", "—").upper(),
                _fmt(seg.get("diameter_mm"), 0),
                _fmt(s["L_m"], 1),
                _fmt(s["v"],   3),
                f"{int(s['Re']):,}",
                _fmt(s["f"],   5),
                _fmt(s["Hf"],  3),
                _fmt(Hm_seg,   3),
            ])

    if data_rows:
        _col_table(doc, headers, data_rows,
                   col_widths=[0.35, 0.75, 0.85, 0.7, 0.6, 0.7, 0.85, 0.75, 0.65, 0.65])
    else:
        _para(doc, "No pipe segments defined.", italic=True)
    doc.add_paragraph()

    if not hyd:
        _para(doc, "Hydraulic compute not yet run — results not available.", italic=True)
        return

    _heading(doc, "4.4 Head Budget Summary", level=2)

    q_v,   q_u   = _us(us, Q,                          "flow")
    vel_v, vel_u  = _us(us, hyd.get("velocity_ms"),    "velocity")
    hs_v,  hs_u   = _us(us, hyd.get("static_head_m"), "head")
    hf_v,  hf_u   = _us(us, hyd.get("friction_head_m"), "head")
    hm_v,  hm_u   = _us(us, hyd.get("minor_head_m"),  "head")
    tdh_v, tdh_u  = _us(us, hyd.get("tdh_m"),         "head")

    rows = [
        ("Design flow Q",           f"{_fmt(q_v, 1)} {q_u}"),
        ("Pipe velocity V",         f"{_fmt(vel_v, 3)} {vel_u}"),
        ("Reynolds number Re",      f"{(hyd.get('reynolds_number') or 0):,.0f}"),
        ("Darcy friction factor f", _fmt(hyd.get("friction_factor"), 5)),
        ("Static head Hs",          f"{_fmt(hs_v)} {hs_u}"),
        ("Friction head Hf",        f"{_fmt(hf_v)} {hf_u}"),
        ("Minor head Hm",           f"{_fmt(hm_v)} {hm_u}"),
        ("Total Dynamic Head TDH",  f"{_fmt(tdh_v)} {tdh_u}  ← design duty"),
    ]
    _kv_table(doc, rows)
    doc.add_paragraph()

    sys_pts = hyd.get("system_curve", []) or []
    if sys_pts:
        _heading(doc, "4.5 System Curve Data Points", level=2)
        headers   = ["Q (m³/h)", "H (m)"]
        data_rows = [[_fmt(p.get("Q_m3h"), 1), _fmt(p.get("H_m"))] for p in sys_pts]
        _col_table(doc, headers, data_rows, col_widths=[1.5, 1.5])
        doc.add_paragraph()

    fig_bytes = fig_system_curve(draft, us=us)
    if fig_bytes:
        _embed_figure(doc, fig_bytes,
                      "Figure 2 — Pump H-Q and system curve overlay with duty operating point(s)")
    doc.add_paragraph()


