def build_document(draft: dict) -> Document:
    """
    Build a full engineering Word report from a ProjectDraft dict.

    Parameters
    ----------
    draft : dict
        Serialised ProjectDraft — same payload used by the Excel exporter.

    Returns
    -------
    docx.Document
        Fully populated python-docx Document object.
    """
    draft = draft or {}
    meta  = draft.get("meta", {}) or {}

    doc = Document()

    # Page margins
    for section in doc.sections:
        section.top_margin    = Inches(1.0)
        section.bottom_margin = Inches(1.0)
        section.left_margin   = Inches(1.2)
        section.right_margin  = Inches(1.2)

    # Footer with page numbers
    _add_page_numbers(doc)

    # Title page (stamp + revision table)
    _title_page(doc, meta)

    # Body sections
    _executive_summary(doc, draft)
    _system_description(doc, draft)
    _basis_of_design(doc, draft)
    _hydraulics_section(doc, draft)
    _pump_section(doc, draft)
    _wetwell_section(doc, draft)
    _engineering_checks_section(doc, draft)
    _surge_section(doc, draft)

    # Appendices
    _appendix_inputs(doc, draft)
    _appendix_pump_curves(doc, draft)
    _appendix_surge_timeseries(doc, draft)
    _appendix_roughness_ref(doc)

    return doc


def _doc_to_bytes(doc: Document) -> bytes:
    """Serialise a Document to a .docx byte string."""
    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf.read()
