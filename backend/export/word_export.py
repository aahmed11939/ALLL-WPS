"""
Word / DOCX design report builder — ALLL WPS Designer.

Produces a stamped engineering memorandum with:
  - Title page with project metadata, stamp block, and revision table
  - Executive summary
  - System description / basis of design
  - Hydraulic calculations (Darcy-Weisbach equations, head budget, system curve)
  - Pump analysis (H-Q / η / P / NPSHr curves, operating points, VFD)
  - Wet well sizing and pump cycling (AWWA M32)
  - Engineering checks summary
  - Surge / water hammer analysis (Joukowsky + MOC + protection comparison)
  - Appendices: full inputs, pump curve data table, surge time-series snapshot,
                pipe roughness reference

Figures are generated by backend.engine.word_figures and embedded as PNGs.
"""

