# ---------------------------------------------------------------------------
# Physical constants (shared with Excel exporter)
# ---------------------------------------------------------------------------

G_ACC      = 9.80665   # m/s²
RHO_WATER  = 998.2     # kg/m³  (20 °C)
MU_WATER   = 1.002e-3  # Pa·s   (20 °C)

ROUGHNESS_M: dict[str, float] = {
    "pvc":              0.0000015,
    "hdpe":             0.0000015,
    "upvc":             0.0000015,
    "dicl":             0.00025,
    "ductile_iron":     0.00025,
    "steel":            0.000046,
    "ac":               0.00003,
    "asbestos_cement":  0.00003,
    "concrete":         0.0003,
    "grp":              0.00003,
    "frp":              0.00003,
    "default":          0.0001,
}

