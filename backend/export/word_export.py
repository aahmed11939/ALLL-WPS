def _heading(doc: Document, text: str, level: int = 1) -> None:
    p   = doc.add_heading(text, level=level)
    run = p.runs[0] if p.runs else p.add_run(text)
    if level == 1:
        run.font.color.rgb = NAVY
        run.font.size      = Pt(14)
    elif level == 2:
        run.font.color.rgb = TEAL
        run.font.size      = Pt(12)
    else:
        run.font.color.rgb = GREY
        run.font.size      = Pt(11)


def _para(doc: Document, text: str, bold: bool = False,
          italic: bool = False, size: int = 10) -> None:
    p   = doc.add_paragraph()
    run = p.add_run(text)
    run.bold   = bold
    run.italic = italic
    run.font.size = Pt(size)


def _equation(doc: Document, text: str) -> None:
    """Render an equation-style paragraph in Courier New 8 pt, indented."""
    p   = doc.add_paragraph()
    p.paragraph_format.left_indent = Inches(0.4)
    run = p.add_run(text)
    run.font.name  = "Courier New"
    run.font.size  = Pt(8)
    run.font.color.rgb = RGBColor(0x33, 0x33, 0x33)


def _hline(doc: Document) -> None:
    """Insert a thin horizontal rule via paragraph border."""
    p    = doc.add_paragraph()
    pPr  = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bot  = OxmlElement("w:bottom")
    bot.set(qn("w:val"),   "single")
    bot.set(qn("w:sz"),    "6")
    bot.set(qn("w:color"), "1F3864")
    pBdr.append(bot)
    pPr.append(pBdr)


def _page_break(doc: Document) -> None:
    doc.add_page_break()


def _kv_table(doc: Document, rows: list[tuple[str, str]],
              col_widths: tuple[float, float] = (2.5, 3.5)) -> None:
    """Compact 2-column key-value table with navy key cells."""
    if not rows:
        return
    tbl = doc.add_table(rows=len(rows), cols=2)
    tbl.style = "Table Grid"
    for i, (k, v) in enumerate(rows):
        key_c = tbl.rows[i].cells[0]
        val_c = tbl.rows[i].cells[1]
        key_c.text = k
        val_c.text = str(v)
        for run in key_c.paragraphs[0].runs:
            run.bold           = True
            run.font.size      = Pt(9)
        for run in val_c.paragraphs[0].runs:
            run.font.size = Pt(9)
        _set_cell_shading(key_c, "D0E4F5")
        _set_cell_borders(key_c)
        _set_cell_borders(val_c)
        key_c.width = Inches(col_widths[0])
        val_c.width = Inches(col_widths[1])


def _col_table(doc: Document, headers: list[str],
               data_rows: list[list[str]],
               col_widths: list[float] | None = None) -> None:
    """Multi-column data table with navy header row."""
    if not data_rows:
        return
    n_cols = len(headers)
    tbl    = doc.add_table(rows=1 + len(data_rows), cols=n_cols)
    tbl.style = "Table Grid"

    hdr_row = tbl.rows[0]
    for j, h in enumerate(headers):
        c = hdr_row.cells[j]
        c.text = h
        for run in c.paragraphs[0].runs:
            run.bold           = True
            run.font.size      = Pt(9)
            run.font.color.rgb = WHITE
        _set_cell_shading(c, "1F3864")
        _set_cell_borders(c)
        if col_widths:
            c.width = Inches(col_widths[j])

    for i, dr in enumerate(data_rows):
        bg  = "F2F5F8" if i % 2 == 1 else "FFFFFF"
        row = tbl.rows[i + 1]
        for j, val in enumerate(dr):
            c = row.cells[j]
            c.text = str(val)
            for run in c.paragraphs[0].runs:
                run.font.size = Pt(9)
            _set_cell_shading(c, bg)
            _set_cell_borders(c)


def _embed_figure(doc: Document, fig_bytes: bytes, caption: str = "",
                  width_in: float = FIGURE_WIDTH_IN) -> None:
    """Embed a PNG byte string as a centred figure with optional caption."""
    buf = io.BytesIO(fig_bytes)
    p   = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(buf, width=Inches(width_in))
    if caption:
        cap = doc.add_paragraph(caption)
        cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        if cap.runs:
            cap.runs[0].italic    = True
            cap.runs[0].font.size = Pt(9)


