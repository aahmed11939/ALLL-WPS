# ---------------------------------------------------------------------------
# Unit conversion helpers
# ---------------------------------------------------------------------------

def _us(unit_system: str, val: float | None, kind: str) -> tuple[float | None, str]:
    """Convert SI value → display unit. Returns (converted_val, unit_label)."""
    if val is None:
        return None, "—"
    if unit_system != "US":
        labels = {
            "flow": "m³/h", "head": "m", "pressure": "kPa",
            "velocity": "m/s", "length": "m", "volume": "m³",
            "power": "kW", "temp": "°C",
        }
        return val, labels.get(kind, "—")
    conv = {
        "flow":     (val * 4.40287,      "gpm"),
        "head":     (val * 3.28084,      "ft"),
        "pressure": (val * 0.14504,      "psi"),
        "velocity": (val * 3.28084,      "ft/s"),
        "length":   (val * 3.28084,      "ft"),
        "volume":   (val * 264.172,      "gal"),
        "power":    (val * 1.34102,      "hp"),
        "temp":     (val * 9 / 5 + 32,   "°F"),
    }
    return conv.get(kind, (val, "—"))


def _fmt(val: float | None, dp: int = 2) -> str:
    if val is None:
        return "—"
    return f"{val:,.{dp}f}"


# ---------------------------------------------------------------------------
# Per-segment Darcy-Weisbach computation (mirrors Excel _seg_darcy helper)
# ---------------------------------------------------------------------------

def _friction_factor_sw(Re: float, eps_D: float) -> float:
    """Swamee-Jain explicit approximation of Darcy-Weisbach f."""
    if Re < 2300:
        return 64.0 / max(Re, 1.0)
    denom = math.log10(eps_D / 3.7 + 5.74 / max(Re, 1.0) ** 0.9)
    return 0.25 / denom ** 2


def _seg_darcy(Q_m3h: float, seg: dict) -> dict:
    """Compute per-segment Darcy-Weisbach hydraulics from geometry + flow."""
    D_m   = seg.get("diameter_mm", 150.0) / 1000.0
    L_m   = seg.get("length_m", 0.0)
    mat   = seg.get("material", "default").lower()
    eps   = ROUGHNESS_M.get(mat, ROUGHNESS_M["default"])
    A     = math.pi * D_m ** 2 / 4.0
    Q_m3s = Q_m3h / 3600.0
    v     = Q_m3s / max(A, 1e-9)
    Re    = RHO_WATER * v * D_m / MU_WATER
    eps_D = eps / max(D_m, 1e-9)
    f     = _friction_factor_sw(Re, eps_D)
    Hf    = f * L_m / D_m * v ** 2 / (2 * G_ACC)
    return {"v": v, "Re": Re, "f": f, "Hf": Hf, "D_m": D_m, "L_m": L_m}


