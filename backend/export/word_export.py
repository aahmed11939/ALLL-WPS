_LOGO_PATH = Path(__file__).parent / "wps_logo.png"


def _title_page(doc: Document, meta: dict) -> None:
    doc.add_paragraph()
    doc.add_paragraph()

    # Company logo — centred above the hero title
    if _LOGO_PATH.exists():
        logo_para = doc.add_paragraph()
        logo_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        logo_para.add_run().add_picture(str(_LOGO_PATH), width=Inches(2.5))
        doc.add_paragraph()

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    tr = title.add_run("ALLL WPS DESIGNER")
    tr.bold           = True
    tr.font.size      = Pt(22)
    tr.font.color.rgb = NAVY

    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sr = sub.add_run("Pump Station Design Report")
    sr.font.size      = Pt(16)
    sr.font.color.rgb = TEAL

    doc.add_paragraph()
    _hline(doc)
    doc.add_paragraph()

    # Document stamp block
    stamp_rows: list[tuple[str, str]] = [
        ("Project",   meta.get("name",      "—")),
        ("Client",    meta.get("client",     "—")),
        ("Job No.",   meta.get("job_number", "—")),
        ("Date",      meta.get("date",       str(_date.today()))),
        ("Engineer",  meta.get("engineer",   "—")),
        ("Status",    "Preliminary"),
    ]
    _kv_table(doc, stamp_rows, col_widths=(2.0, 4.0))

    doc.add_paragraph()

    # Revision table — Rev 0 baseline row
    rev_headers = ["Rev", "Date", "Description", "Prepared by", "Checked by"]
    rev_rows    = [
        ["0",
         meta.get("date", str(_date.today())),
         "Preliminary issue for review",
         meta.get("engineer", "—"),
         "—"],
    ]
    _col_table(doc, rev_headers, rev_rows,
               col_widths=[0.4, 1.0, 2.6, 1.2, 1.0])

    if meta.get("notes"):
        doc.add_paragraph()
        _para(doc, "Design Notes:", bold=True)
        _para(doc, meta["notes"])

    _page_break(doc)


