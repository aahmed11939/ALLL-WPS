def _system_description(doc: Document, draft: dict) -> None:
    _heading(doc, "2. System Description")

    us    = draft.get("unitSystem", "SI")
    Q     = draft.get("designFlow_m3h", 0) or 0
    up    = draft.get("upstreamNode",   {}) or {}
    dn    = draft.get("downstreamNode", {}) or {}
    suct  = draft.get("suction",        {}) or {}
    disc  = draft.get("discharge",      {}) or {}

    static = dn.get("elevation_m", 0) - up.get("elevation_m", 0)
    q_v, q_u = _us(us, Q, "flow")
    hs_v, hs_u = _us(us, static, "head")

    _para(doc, (
        f"The pump station transfers {_fmt(q_v, 1)} {q_u} of potable water against a "
        f"static head of {_fmt(hs_v)} {hs_u}. "
        f"The suction side is at elevation {_fmt(up.get('elevation_m'), 2)} m and the "
        f"discharge is at elevation {_fmt(dn.get('elevation_m'), 2)} m above datum."
    ))

    s_segs = suct.get("segments", []) or []
    d_segs = disc.get("segments", []) or []
    s_len  = sum(s.get("length_m", 0) for s in s_segs)
    d_len  = sum(s.get("length_m", 0) for s in d_segs)
    s_mats = ", ".join(sorted({s.get("material", "").upper() for s in s_segs if s.get("material")}))
    d_mats = ", ".join(sorted({s.get("material", "").upper() for s in d_segs if s.get("material")}))

    doc.add_paragraph()
    _para(doc, (
        f"The suction pipeline comprises {len(s_segs)} segment(s) totalling {_fmt(s_len, 1)} m "
        f"(material: {s_mats or '—'}, ΣK = {_fmt(suct.get('accessories_K_sum', 0), 3)}). "
        f"The discharge pipeline comprises {len(d_segs)} segment(s) totalling {_fmt(d_len, 1)} m "
        f"(material: {d_mats or '—'}, ΣK = {_fmt(disc.get('accessories_K_sum', 0), 3)})."
    ))
    doc.add_paragraph()


