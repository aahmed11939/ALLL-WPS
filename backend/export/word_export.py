def _engineering_checks_section(doc: Document, draft: dict) -> None:
    _heading(doc, "7. Engineering Checks")

    hyd  = draft.get("hydraulicsResult") or {}
    pump = draft.get("pumpResult")       or {}
    cw   = draft.get("clearwellResult")  or {}
    us   = draft.get("unitSystem", "SI")

    checks: list[tuple[str, str, str]] = []

    if hyd:
        vel = hyd.get("velocity_ms", 0) or 0
        vel_v, vel_u = _us(us, vel, "velocity")
        v_ok = 0.5 <= vel <= 3.0
        checks.append(("Pipe velocity", f"{_fmt(vel_v, 3)} {vel_u}",
                        "OK" if v_ok else "WARNING"))

        re = hyd.get("reynolds_number", 0) or 0
        checks.append(("Reynolds number", f"{re:,.0f}",
                        "OK" if re > 4000 else "INFO"))

    ops = pump.get("operating_points", []) if pump else []
    for op in ops:
        margin = op.get("npsh_margin_m")
        if margin is not None:
            sev = "OK" if margin >= 0.6 else ("WARNING" if margin >= 0 else "CRITICAL")
            checks.append((f"NPSH margin (n={op.get('n_pumps', 1)})",
                            f"{_fmt(margin)} m", sev))
        eta = op.get("eta_pct")
        if eta is not None:
            checks.append((f"Pump efficiency (n={op.get('n_pumps', 1)})",
                            f"{_fmt(eta, 1)} %", "OK" if eta >= 60 else "WARNING"))

    if cw and cw.get("active"):
        for cr in cw.get("cycle_results", []) or []:
            s = "OK" if cr.get("cycles_ok") else "WARNING"
            checks.append((f"Pump cycles — {cr.get('label', '')}",
                            f"{_fmt(cr.get('cycles_per_hour'), 2)} /hr", s))
        dt_ok = cw.get("detention_ok")
        if dt_ok is not None:
            checks.append(("Detention time",
                            f"{_fmt(cw.get('detention_time_min'), 1)} min",
                            "OK" if dt_ok else "WARNING"))

    if not checks:
        _para(doc, "No checks available — run analyses first.", italic=True)
        return

    COLOR_MAP = {"OK": "27AE60", "WARNING": "F39C12", "CRITICAL": "E74C3C", "INFO": "2980B9"}
    tbl = doc.add_table(rows=1 + len(checks), cols=3)
    tbl.style = "Table Grid"

    for j, h in enumerate(["Parameter", "Value", "Status"]):
        c = tbl.rows[0].cells[j]
        c.text = h
        for run in c.paragraphs[0].runs:
            run.bold           = True
            run.font.size      = Pt(9)
            run.font.color.rgb = WHITE
        _set_cell_shading(c, "1F3864")
        _set_cell_borders(c)

    for i, (param, val, status) in enumerate(checks):
        row = tbl.rows[i + 1]
        row.cells[0].text = param
        row.cells[1].text = val
        row.cells[2].text = status
        bg = "F2F5F8" if i % 2 == 1 else "FFFFFF"
        for cell in row.cells:
            for run in cell.paragraphs[0].runs:
                run.font.size = Pt(9)
            _set_cell_borders(cell)
            _set_cell_shading(cell, bg)
        status_c = row.cells[2]
        _set_cell_shading(status_c, COLOR_MAP.get(status, "FFFFFF"))
        if status != "OK":
            for run in status_c.paragraphs[0].runs:
                run.bold           = True
                run.font.color.rgb = WHITE

    doc.add_paragraph()

    # Engineering recommendations for any non-OK check
    failed = [(p, s) for p, v, s in checks if s not in ("OK", "INFO")]
    if failed:
        _heading(doc, "7.1 Engineering Recommendations", level=2)
        for param, status in failed:
            rec_key = next((k for k in _RECOMMENDATIONS if k.lower() in param.lower()), None)
            rec_text = _RECOMMENDATIONS.get(rec_key or "", "Review and remediate before proceeding.")
            p = doc.add_paragraph(style="List Bullet")
            run_bold = p.add_run(f"{param} [{status}]: ")
            run_bold.bold      = True
            run_bold.font.size = Pt(9)
            run_rec  = p.add_run(rec_text)
            run_rec.font.size  = Pt(9)
        doc.add_paragraph()


