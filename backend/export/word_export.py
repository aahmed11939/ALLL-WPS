def _surge_section(doc: Document, draft: dict) -> None:
    _heading(doc, "8. Surge / Water Hammer Analysis")

    surge = draft.get("waterHammerResult") or {}
    moc   = draft.get("mocResult")         or {}
    wi    = draft.get("whatIfResult")      or {}

    # 8.1 Joukowsky
    _heading(doc, "8.1 Joukowsky Instantaneous Analysis (Mode A)", level=2)
    _para(doc, (
        "The Joukowsky equation gives the maximum pressure rise for an "
        "instantaneous pump trip or valve closure (conservative upper bound):"
    ))
    _equation(doc, "ΔH = a · ΔV / g")
    doc.add_paragraph()

    if surge:
        rows = [
            ("Wave speed a",           f"{_fmt(surge.get('wave_speed_ms'), 0)} m/s"),
            ("Initial velocity V₀",    f"{_fmt(surge.get('V0_ms'), 3)} m/s"),
            ("Joukowsky ΔH",           f"{_fmt(surge.get('delta_H_joukowsky_m'))} m"),
            ("Joukowsky ΔP",           f"{_fmt(surge.get('delta_P_joukowsky_kPa'), 0)} kPa"),
            ("Operating head H₀",      f"{_fmt(surge.get('H_operating_m'))} m"),
            ("Max transient head",     f"{_fmt(surge.get('max_pressure_head_m'))} m"),
            ("Min transient head",     f"{_fmt(surge.get('min_pressure_head_m'))} m"),
            ("Cavitation risk",        "YES" if surge.get("cavitation_risk") else "No"),
            ("Vacuum risk",            "YES" if surge.get("vacuum_risk")     else "No"),
            ("Characteristic time Tc", f"{_fmt(surge.get('T_char_s'), 3)} s"),
        ]
        _kv_table(doc, rows)
        doc.add_paragraph()
    else:
        _para(doc, "Surge quick analysis not run.", italic=True)

    # 8.2 MOC
    if moc:
        _heading(doc, "8.2 Method of Characteristics — Full Transient Simulation", level=2)
        _para(doc, (
            "The Method of Characteristics (MOC) solves the 1D transient pipe-flow "
            "PDEs on a characteristic grid, capturing wave reflections, attenuation, "
            "and node-by-node pressure histories."
        ))
        _equation(doc, "∂H/∂t + (a²/g)·∂V/∂x = 0    and    ∂V/∂t + g·∂H/∂x + f·V|V|/(2D) = 0")
        doc.add_paragraph()

        rows = [
            ("Pipe segments N",        str(moc.get("N", "—"))),
            ("Spatial step Δx",        f"{_fmt(moc.get('dx_m'))} m"),
            ("Time step Δt",           f"{_fmt(moc.get('dt_s'), 4)} s"),
            ("Courant number",         f"{_fmt(moc.get('courant'), 3)}"),
            ("Simulation duration",    f"{_fmt(moc.get('t_total_s'), 1)} s"),
            ("Global max head H_max",  f"{_fmt(moc.get('global_max_H_m'))} m"),
            ("Global min head H_min",  f"{_fmt(moc.get('global_min_H_m'))} m"),
            ("Cavitation locations",   str(len(moc.get("cavitation_x_m", []) or []))),
        ]
        _kv_table(doc, rows)
        doc.add_paragraph()

        fig_suct = fig_surge_envelope_suction(draft)
        if fig_suct:
            _embed_figure(doc, fig_suct,
                          "Figure 4a — MOC pressure envelope: suction pipeline")

        fig_disc = fig_surge_envelope_discharge(draft)
        if fig_disc:
            _embed_figure(doc, fig_disc,
                          "Figure 4b — MOC pressure envelope: discharge pipeline")

        fig_hist = fig_moc_histories(draft)
        if fig_hist:
            _embed_figure(doc, fig_hist,
                          "Figure 5 — MOC head time histories at key observation nodes")

        doc.add_paragraph()

        obs = moc.get("observations", []) or []
        if obs:
            _heading(doc, "8.3 Time History Summary at Key Nodes", level=2)
            headers = ["Node", "x (m)", "H max (m)", "H min (m)"]
            data_rows = []
            for ob in obs:
                hist   = ob.get("history", []) or []
                h_vals = [h.get("H_m", 0) for h in hist]
                data_rows.append([
                    ob.get("label", ""),
                    _fmt(ob.get("x_m")),
                    _fmt(max(h_vals) if h_vals else None),
                    _fmt(min(h_vals) if h_vals else None),
                ])
            _col_table(doc, headers, data_rows, col_widths=[2.0, 1.0, 1.2, 1.2])
            doc.add_paragraph()

    # 8.4 Protection comparison
    if wi and (wi.get("baseline") or wi.get("device_runs")):
        _heading(doc, "8.4 Surge Protection Device Comparison", level=2)

        baseline = wi.get("baseline") or {}
        runs     = wi.get("device_runs", []) or []
        headers  = ["Scenario", "H max (m)", "H min (m)", "ΔH reduction (m)", "Cavitation"]
        data_rows = []
        for r in [baseline] + runs:
            data_rows.append([
                r.get("label", "Baseline"),
                _fmt(r.get("global_max_H_m")),
                _fmt(r.get("global_min_H_m")),
                _fmt(r.get("max_surge_reduction_m")),
                "Yes" if r.get("cavitation_risk") else "No",
            ])
        _col_table(doc, headers, data_rows, col_widths=[2.0, 1.0, 1.0, 1.2, 1.0])
        doc.add_paragraph()

        fig_prot = fig_protection_comparison(draft)
        if fig_prot:
            _embed_figure(doc, fig_prot,
                          "Figure 6 — Surge protection: peak pressure comparison by device")

        for n in wi.get("assumption_notes", []) or []:
            _para(doc, f"  • {n}")
        doc.add_paragraph()


